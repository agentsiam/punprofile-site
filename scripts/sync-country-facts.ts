/**
 * Copies the country quick facts into the app, for the report's country page.
 *
 *   npx tsx scripts/sync-country-facts.ts
 *
 * Source: the YAML block in `country-facts.md` in the coaching repo's
 * `punprofile-context/ctxt-research/`, approved as the source of truth by Paul
 * on 20/11/2026.
 *
 * Same reason as `sync-market-snapshot.ts`: the app cannot read across repos at
 * runtime, so this is a dated snapshot.
 *
 * What is deliberately not emitted: any route or field the facts file marks as
 * not yet confirmed. A route field ending `_verify: true`, `_hold`, or a route
 * carrying `verify: true` or `hold`, stays out. A figure that has not been read
 * on the government page is never printed to a candidate. Where that leaves a
 * route with no salary, the page says so rather than guessing.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import yaml from "js-yaml";

export const SOURCE =
  "../punprofile-career-coaching/punprofile-context/ctxt-research/country-facts.md";
const OUT = "src/lib/content/country-facts.generated.ts";

const BLUE_CARD_PARTNER =
  "Your partner may work, with no waiting period (EU Blue Card rules, Directive 2021/1883 Article 17(6))";

type Raw = Record<string, unknown>;

export interface CountryRoute {
  name: string;
  employer?: string;
  salary?: string;
  salaryAsOf?: string;
  salarySource?: string;
  partner?: string;
  processing?: string;
  processingUrl?: string;
  url?: string;
}
export interface CountryFacts {
  country: string;
  capital: string;
  timeFromBangkok: string;
  note?: string;
  otherRoutes?: string;
  routes: CountryRoute[];
}

function str(v: unknown): string | undefined {
  return typeof v === "string" && v.trim() ? v.trim() : typeof v === "number" ? String(v) : undefined;
}

export function cleanRoute(r: Raw): CountryRoute | null {
  const name = str(r.name);
  if (!name) return null;
  const routeUnconfirmed = r.verify === true || r.hold !== undefined;
  const ok = (field: string) => r[`${field}_verify`] !== true && r[`${field}_hold`] === undefined;
  const out: CountryRoute = { name };
  if (ok("employer") && str(r.employer)) out.employer = str(r.employer);
  if (!routeUnconfirmed && ok("salary") && str(r.salary)) {
    out.salary = str(r.salary);
    out.salaryAsOf = str(r.salary_as_of);
    out.salarySource = str(r.salary_source);
  }
  if (ok("partner") && r.partner_hold !== true && str(r.partner)) {
    out.partner = r.partner === "BLUE_CARD_PARTNER" ? BLUE_CARD_PARTNER : str(r.partner);
  }
  if (ok("processing") && str(r.processing)) {
    out.processing = str(r.processing);
    if (str(r.processing_url)) out.processingUrl = str(r.processing_url);
  }
  if (ok("url") && str(r.url)) out.url = str(r.url);
  else if (str(r.url_fallback)) out.url = str(r.url_fallback);
  return out;
}

export function parse(md: string): CountryFacts[] {
  const start = md.indexOf("```yaml\n");
  if (start < 0) throw new Error("country-facts.md: no ```yaml block found");
  const end = md.indexOf("```", start + 8);
  const doc = yaml.load(md.slice(start + 8, end)) as Raw[];
  if (!Array.isArray(doc) || doc.length === 0) throw new Error("country-facts.md: YAML block is empty");
  return doc.map((c) => {
    const routes = ((c.routes as Raw[]) ?? []).map(cleanRoute).filter((r): r is CountryRoute => r !== null);
    const row: CountryFacts = {
      country: str(c.country)!,
      capital: str(c.capital)!,
      timeFromBangkok: str(c.time_from_bangkok)!,
      routes,
    };
    if (str(c.note)) row.note = str(c.note);
    if (str(c.other_routes)) row.otherRoutes = str(c.other_routes);
    return row;
  });
}

function main() {
  if (!existsSync(SOURCE)) {
    console.error(`Missing source: ${SOURCE}. Nothing written.`);
    process.exit(1);
  }
  const md = readFileSync(SOURCE, "utf8");
  const researched = /^researched:\s*(\S+)/m.exec(md)?.[1] ?? "";
  const facts = parse(md);
  const body = `// Generated by scripts/sync-country-facts.ts from the coaching repo's country-facts.md.
// Do not edit. Rerun the script.
import type { CountryFacts } from "../../../scripts/sync-country-facts";

export const COUNTRY_FACTS_RESEARCHED = ${JSON.stringify(researched)};
export const COUNTRY_FACTS: CountryFacts[] = ${JSON.stringify(facts, null, 2)};
`;
  writeFileSync(OUT, body);
  const routes = facts.reduce((n, c) => n + c.routes.length, 0);
  console.log(`Wrote ${OUT}: ${facts.length} countries, ${routes} routes.`);
}

if (process.argv[1]?.endsWith("sync-country-facts.ts")) main();
